def generate_health_recommendations(disease_name, risk_level="Moderate", severity_level="Moderate", symptoms=None):
    """
    Generates a structured health recommendation dictionary based on prediction outputs.
    """
    d_lower = str(disease_name).lower() if disease_name else ""
    
    matched_key = None
    for key in RECOMMENDATION_REGISTRY:
        if key in d_lower:
            matched_key = key
            break

    if matched_key:
        rec_data = RECOMMENDATION_REGISTRY[matched_key].copy()
    else:
        rec_data = GENERAL_ADVISORY.copy()

    # Customize urgency and lifestyle guidance based on Risk Level
    if risk_level in ["High", "Critical"]:
        rec_data["urgencyAlert"] = f"Priority Advisory: High Risk Level detected ({risk_level}). Prompt specialist consultation is strongly recommended."
    else:
        rec_data["urgencyAlert"] = f"Standard Advisory: Moderate/Low Risk Level ({risk_level}). Monitor symptoms and schedule routine consultation."

    rec_data["disclaimer"] = (
        "AI-Generated Health Advisory: These supportive care recommendations are AI-generated wellness guidelines "
        "based on your predicted condition and risk score. They do not constitute an official medical diagnosis "
        "or clinical prescription. Please consult a qualified doctor for clinical evaluation."
    )
    
    rec_data["targetCondition"] = disease_name
    rec_data["assessedRiskLevel"] = risk_level
    rec_data["assessedSeverity"] = severity_level

    return rec_data
