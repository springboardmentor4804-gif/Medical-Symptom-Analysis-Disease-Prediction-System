def parse_date(date_str: str) -> datetime:
    if not date_str or date_str == "Unknown":
        return datetime.min
    for fmt in ("%m/%d/%Y", "%Y-%m-%d", "%d/%m/%Y", "%Y/%m/%d"):
        try:
            return datetime.strptime(date_str, fmt)
        except ValueError:
            continue
    return datetime.min

def get_trend_sort_key(item: dict) -> datetime:
    k = item.get("date", "")
    if not k or k == "Unknown":
        return datetime.min
    
    # Try parsing as standard daily formats
    for fmt in ("%m/%d/%Y", "%Y-%m-%d", "%d/%m/%Y", "%Y/%m/%d"):
        try:
            return datetime.strptime(k, fmt)
        except ValueError:
            continue
            
    # Try parsing weekly format e.g. 2026-W35
    if "-W" in k:
        try:
            parts = k.split("-W")
            year = int(parts[0])
            week = int(parts[1])
            return datetime.strptime(f"{year} {week} 1", "%G %V %u")
        except Exception:
            pass
            
    # Try parsing monthly format e.g. Aug 2026
    for fmt in ("%b %Y", "%B %Y"):
        try:
            return datetime.strptime(k, fmt)
        except ValueError:
            continue
            
    return datetime.min

router = APIRouter(prefix="/api/analytics", tags=["analytics"])

@router.get("/")
async def get_analytics(current_user: dict = Depends(get_current_user)):
    # 1. Enforce RBAC
    if current_user.get("role") != "doctor":
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Access denied. Only doctors can view healthcare analytics."
        )

    db = get_db()
    
    # 2. Fetch all patients and extract assessments
    patients = db.users.find({"role": "patient"})
    
    all_assessments = []
    
    # We will also keep track of patients for the high-risk table
    for p in patients:
        history = p.get("medicalHistory", [])
        for item in history:
            # Assessments generated by AI have 'details' field populated
            if isinstance(item, dict) and item.get("details"):
                details = item["details"]
                all_assessments.append({
                    "patient_id": str(p["_id"]),
                    "patient_name": p.get("name", "Unknown"),
                    "date": item.get("date", ""),
                    "condition": item.get("condition", ""),
                    "confidence": details.get("primaryProb", 0),
                    "risk_cat": details.get("riskCat", "Low Risk"),
                    "severity": details.get("severity", "Moderate"),
                    "item_raw": item
                })

    total_assessments = len(all_assessments)
    
    if total_assessments == 0:
        return {
            "totalAssessments": 0,
            "mostPredictedDisease": None,
            "averageConfidence": 0,
            "highRisk": 0,
            "moderateRisk": 0,
            "lowRisk": 0,
            "diseaseDistribution": [],
            "riskDistribution": [],
            "confidenceDistribution": [],
            "symptomDistribution": [],
            "diseaseTrends": [],
            "riskTrends": [],
            "highRiskCases": []
        }

    # 3. Aggregations
    disease_counts = defaultdict(int)
    risk_counts = {"High Risk": 0, "Moderate Risk": 0, "Low Risk": 0}
    symptom_counts = defaultdict(int)
    total_confidence = 0
    confidence_buckets = {
        "<60%": 0,
        "60-70%": 0,
        "70-80%": 0,
        "80-90%": 0,
        ">90%": 0
    }
    
    disease_trends_raw = defaultdict(lambda: defaultdict(int))
    risk_trends_raw = defaultdict(lambda: defaultdict(int))
    
    high_risk_cases = []

    for idx, a in enumerate(all_assessments):
        # Disease
        disease = a["condition"]
        if disease:
            disease_counts[disease] += 1
            
        # Confidence
        conf = a["confidence"]
        total_confidence += conf
        if conf < 60:
            confidence_buckets["<60%"] += 1
        elif conf < 70:
            confidence_buckets["60-70%"] += 1
        elif conf < 80:
            confidence_buckets["70-80%"] += 1
        elif conf < 90:
            confidence_buckets["80-90%"] += 1
        else:
            confidence_buckets[">90%"] += 1
            
        # Risk
        risk = a["risk_cat"]
        if risk in risk_counts:
            risk_counts[risk] += 1
        else:
            risk_counts["Low Risk"] += 1 # fallback
            
        # Symptoms
        symptoms = a["item_raw"].get("details", {}).get("symptoms", [])
        if isinstance(symptoms, list):
            for sym in symptoms:
                symptom_counts[sym.lower()] += 1
            
        # Trends (by Date - simplified daily grouping based on string date)
        # Assuming date format like MM/DD/YYYY or similar
        date_str = a["date"]
        if not date_str:
            date_str = "Unknown"
            
        if disease:
            disease_trends_raw[date_str][disease] += 1
        risk_trends_raw[date_str][risk] += 1
        
        # High Risk Cases table
        if risk == "High Risk":
            high_risk_cases.append({
                "id": f"{a['patient_id']}_{idx}",
                "patient_id": a["patient_id"],
                "patient_name": a["patient_name"],
                "condition": a["condition"],
                "confidence": a["confidence"],
                "risk_cat": a["risk_cat"],
                "severity": a["severity"],
                "date": a["date"],
                "report": a["item_raw"]
            })

    # Format output
    most_predicted_disease = max(disease_counts.items(), key=lambda x: x[1])[0] if disease_counts else "None"
    avg_confidence = round(total_confidence / total_assessments, 1) if total_assessments > 0 else 0
    
    disease_distribution = [{"name": k, "value": v} for k, v in disease_counts.items()]
    # Sort for better chart display
    disease_distribution = sorted(disease_distribution, key=lambda x: x["value"], reverse=True)
    
    risk_distribution = [
        {"name": "High Risk", "value": risk_counts["High Risk"]},
        {"name": "Moderate Risk", "value": risk_counts["Moderate Risk"]},
        {"name": "Low Risk", "value": risk_counts["Low Risk"]}
    ]
    
    confidence_distribution = [{"name": k, "value": v} for k, v in confidence_buckets.items()]
    
    symptom_distribution = [{"name": k.title(), "value": v} for k, v in symptom_counts.items()]
    symptom_distribution = sorted(symptom_distribution, key=lambda x: x["value"], reverse=True)[:10] # Top 10
    
    # Trends
    # Flatten trends into an array suitable for Recharts
    # { date: "10/12/2023", "Dengue": 2, "Malaria": 1 }
    disease_trends = []
    for date_str, counts in disease_trends_raw.items():
        entry = {"date": date_str}
        entry.update(counts)
        disease_trends.append(entry)
    
    risk_trends = []
    for date_str, counts in risk_trends_raw.items():
        entry = {"date": date_str}
        entry.update(counts)
        risk_trends.append(entry)
        
    # Sort trends by date chronologically
    disease_trends = sorted(disease_trends, key=lambda x: parse_date(x["date"]))
    risk_trends = sorted(risk_trends, key=lambda x: parse_date(x["date"]))
    
    # Sort high risk cases by date descending
    high_risk_cases.sort(key=lambda x: parse_date(x["date"]), reverse=True)

    return {
        "totalAssessments": total_assessments,
        "mostPredictedDisease": most_predicted_disease,
        "averageConfidence": avg_confidence,
        "highRisk": risk_counts["High Risk"],
        "moderateRisk": risk_counts["Moderate Risk"],
        "lowRisk": risk_counts["Low Risk"],
        "diseaseDistribution": disease_distribution,
        "riskDistribution": risk_distribution,
        "confidenceDistribution": confidence_distribution,
        "symptomDistribution": symptom_distribution,
        "diseaseTrends": disease_trends,
        "riskTrends": risk_trends,
        "highRiskCases": high_risk_cases
    }

@router.get("/trends")
async def get_trends(
    granularity: str = Query("daily", regex="^(daily|weekly|monthly)$"),
    timeRange: int = Query(30, ge=1, le=365),
    disease: Optional[str] = Query(None),
    riskLevel: Optional[str] = Query(None),
    patientId: Optional[str] = Query(None),
    current_user: dict = Depends(get_current_user)
):
    db = get_db()
    
    # 1. Enforce RBAC
    query_filter = {"role": "patient"}
    
    if current_user.get("role") == "patient":
        # Force patientId to current user if they are a patient
        patient_id_to_fetch = str(current_user["_id"])
        query_filter["_id"] = ObjectId(patient_id_to_fetch)
    else:
        # Doctor can filter by patientId
        if patientId:
            try:
                query_filter["_id"] = ObjectId(patientId)
            except Exception:
                raise HTTPException(status_code=400, detail="Invalid patientId")

    patients = db.users.find(query_filter)
    
    # Date cutoff parsing (assuming stored date is MM/DD/YYYY)
    now = datetime.now()
    cutoff_date = now - timedelta(days=timeRange)
    
    all_assessments = []
    
    for p in patients:
        history = p.get("medicalHistory", [])
        for item in history:
            if isinstance(item, dict) and item.get("details"):
                details = item["details"]
                date_str = item.get("date", "")
                
                # Basic date parsing/filtering
                try:
                    # Expecting MM/DD/YYYY or similar. Fallback to basic if error
                    item_date = datetime.strptime(date_str, "%m/%d/%Y") if "/" in date_str else datetime.strptime(date_str, "%Y-%m-%d")
                    if item_date < cutoff_date:
                        continue
                except Exception:
                    pass # Keep if we can't parse date strictly
                
                cond = item.get("condition", "")
                risk = details.get("riskCat", "Low Risk")
                
                if disease and disease.lower() != "all" and cond.lower() != disease.lower():
                    continue
                if riskLevel and riskLevel.lower() != "all" and risk.lower() != riskLevel.lower():
                    continue
                
                # Grouping key
                if granularity == "daily":
                    group_key = date_str
                elif granularity == "weekly":
                    try:
                        dt = datetime.strptime(date_str, "%m/%d/%Y") if "/" in date_str else datetime.strptime(date_str, "%Y-%m-%d")
                        # Year and week number
                        group_key = f"{dt.year}-W{dt.isocalendar()[1]:02d}"
                    except:
                        group_key = date_str
                else: # monthly
                    try:
                        dt = datetime.strptime(date_str, "%m/%d/%Y") if "/" in date_str else datetime.strptime(date_str, "%Y-%m-%d")
                        group_key = f"{dt.strftime('%b %Y')}"
                    except:
                        group_key = date_str

                all_assessments.append({
                    "group_key": group_key,
                    "condition": cond,
                    "confidence": details.get("primaryProb", 0),
                    "risk": risk
                })

    # Aggregations
    disease_trends_raw = defaultdict(lambda: defaultdict(int))
    risk_trends_raw = defaultdict(lambda: {"High Risk": 0, "Moderate Risk": 0, "Low Risk": 0})
    volume_trends_raw = defaultdict(int)
    conf_trends_raw = defaultdict(lambda: {"total": 0, "count": 0})
    
    for a in all_assessments:
        k = a["group_key"]
        if a["condition"]:
            disease_trends_raw[k][a["condition"]] += 1
        risk_trends_raw[k][a["risk"]] += 1
        volume_trends_raw[k] += 1
        conf_trends_raw[k]["total"] += a["confidence"]
        conf_trends_raw[k]["count"] += 1

    # Format
    disease_trends = []
    for k, counts in disease_trends_raw.items():
        entry = {"date": k}
        entry.update(counts)
        disease_trends.append(entry)
        
    risk_trends = []
    for k, counts in risk_trends_raw.items():
        entry = {"date": k, "High": counts["High Risk"], "Moderate": counts["Moderate Risk"], "Low": counts["Low Risk"]}
        risk_trends.append(entry)
        
    assessment_trends = [{"date": k, "Volume": v} for k, v in volume_trends_raw.items()]
    
    confidence_trends = []
    for k, vals in conf_trends_raw.items():
        avg = round(vals["total"] / vals["count"], 1) if vals["count"] > 0 else 0
        confidence_trends.append({"date": k, "AverageConfidence": avg})
        
    # Sort trends chronologically using get_trend_sort_key helper
    disease_trends.sort(key=get_trend_sort_key)
    risk_trends.sort(key=get_trend_sort_key)
    assessment_trends.sort(key=get_trend_sort_key)
    confidence_trends.sort(key=get_trend_sort_key)

    return {
        "diseaseTrends": disease_trends,
        "riskTrends": risk_trends,
        "assessmentTrends": assessment_trends,
        "confidenceTrends": confidence_trends
    }

